# ANN-Based Intelligent Routing in Wireless Sensor Networks
# Source -> Candidate Neighbors -> Destination (Base Station)

import numpy as np
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, confusion_matrix
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense

# =====================================================
# PART 1 : TRAIN ANN FOR NEXT-HOP SELECTION
# =====================================================

N = 5000

energy = np.random.uniform(0,1,N)
dist_bs = np.random.uniform(0,100,N)
hop_dist = np.random.uniform(0,30,N)
lqi = np.random.uniform(0,1,N)
degree = np.random.randint(1,20,N)

X = np.column_stack((energy,
                     dist_bs,
                     hop_dist,
                     lqi,
                     degree))

# Expert Routing Rule
Y = ((energy > 0.6) &
     (dist_bs < 50) &
     (hop_dist < 15) &
     (lqi > 0.7) &
     (degree > 8)).astype(int)

X_train,X_test,Y_train,Y_test = train_test_split(
    X,Y,test_size=0.2,random_state=42)

scaler = StandardScaler()

X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

# ANN Model
model = Sequential([
    Dense(16,activation='relu',input_shape=(5,)),
    Dense(8,activation='relu'),
    Dense(1,activation='sigmoid')
])

model.compile(
    optimizer='adam',
    loss='binary_crossentropy',
    metrics=['accuracy']
)

history = model.fit(
    X_train,
    Y_train,
    epochs=30,
    batch_size=32,
    validation_split=0.2,
    verbose=0
)

pred = (model.predict(X_test,verbose=0) > 0.5).astype(int)

print("ANN Accuracy =",round(accuracy_score(Y_test,pred),4))

# =====================================================
# PART 2 : WSN DEPLOYMENT
# =====================================================

num_nodes = 30

x = np.random.uniform(0,100,num_nodes)
y = np.random.uniform(0,100,num_nodes)

source = 0

BS_x = 50
BS_y = 150

# Candidate neighbor nodes
neighbor_ids = [5, 12, 18, 24]

# Features of neighbors
neighbors = np.array([
    [0.90,30,10,0.95,12],  # Node 5
    [0.45,20,18,0.60,8],   # Node 12
    [0.75,40,12,0.85,10],  # Node 18
    [0.30,15,20,0.40,5]    # Node 24
])

# ANN Scores
scores = model.predict( scaler.transform(neighbors),  verbose=0).flatten()

best_idx = np.argmax(scores)

next_hop = neighbor_ids[best_idx]

print("\nCandidate Neighbor Scores")

for i,node in enumerate(neighbor_ids):
    print("Node",node,"Score =",round(scores[i],4))

print("\nSelected Next-Hop Node =",next_hop)

# =====================================================
# FIGURE 1 : ROUTING TOPOLOGY
# =====================================================

plt.figure(figsize=(9,7))

# Sensor nodes
plt.scatter(x,y,
            s=60,
            c='blue',
            label='Sensor Nodes')

# Source
plt.scatter(x[source],
            y[source],
            s=250,
            c='green',
            marker='o',
            label='Source')

# Destination
plt.scatter(BS_x,
            BS_y,
            s=350,
            c='black',
            marker='p',
            label='Destination (BS)')

# Candidate neighbors
for node in neighbor_ids:

    plt.scatter(x[node],
                y[node],
                s=220,
                c='orange',
                marker='^')

# Possible Paths
for node in neighbor_ids:

    plt.plot(
        [x[source],x[node]],
        [y[source],y[node]],
        '--',
        color='gray',
        linewidth=1.5
    )

    plt.plot(
        [x[node],BS_x],
        [y[node],BS_y],
        '--',
        color='gray',
        linewidth=1.5
    )

# ANN Selected Next-Hop
plt.scatter(x[next_hop],
            y[next_hop],
            s=280,
            c='red',
            marker='s',
            label='ANN Selected Next-Hop')

# Selected Route
plt.plot(
    [x[source],x[next_hop]],
    [y[source],y[next_hop]],
    'g',
    linewidth=4
)

plt.plot(
    [x[next_hop],BS_x],
    [y[next_hop],BS_y],
    'r',
    linewidth=4
)

# Node IDs
for i in range(num_nodes):

    plt.text(
        x[i]+1,
        y[i]+1,
        str(i),
        fontsize=8
    )

# Neighbor Scores
for i,node in enumerate(neighbor_ids):

    plt.text(
        x[node]+2,
        y[node]-2,
        f'S={scores[i]:.2f}',
        color='red',
        fontsize=9
    )

plt.title('ANN-Based Intelligent Routing')

plt.xlabel('X Coordinate')
plt.ylabel('Y Coordinate')

plt.legend()
plt.grid(True)

# =====================================================
# FIGURE 2 : TRAINING ACCURACY
# =====================================================

plt.figure(figsize=(6,4))

plt.plot(history.history['accuracy'],
         linewidth=2)

plt.plot(history.history['val_accuracy'],
         linewidth=2)

plt.xlabel('Epoch')
plt.ylabel('Accuracy')

plt.title('ANN Training Accuracy')

plt.legend(['Training',
            'Validation'])

plt.grid(True)

# =====================================================
# FIGURE 3 : TRAINING LOSS
# =====================================================

plt.figure(figsize=(6,4))

plt.plot(history.history['loss'],
         linewidth=2)

plt.plot(history.history['val_loss'],
         linewidth=2)

plt.xlabel('Epoch')
plt.ylabel('Loss')

plt.title('ANN Training Loss')

plt.legend(['Training',
            'Validation'])

plt.grid(True)

# =====================================================
# FIGURE 4 : Neighbor Scores
# =====================================================

plt.figure(figsize=(6,4))

plt.bar(
    [str(i) for i in neighbor_ids],
    scores
)

plt.xlabel('Neighbor Node')
plt.ylabel('ANN Score')

plt.title('Next-Hop Selection Scores')

plt.grid(True)

plt.show()